"""Render internal routes from OpenAPI Generator's operation manifest."""

import argparse
import json
from pathlib import Path
import re

from contract import check_python_surface, write_model_contract


METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}
PARAMETER = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")


def manifest(path):
    operations = {}
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        name, method, route = line.split()
        if name in operations:
            if operations[name] != (method, route):
                raise ValueError(f"Ambiguous OpenAPI operation: {name}")
        operations[name] = method, route
    return operations


def check_sources(root, pattern, operations):
    references = {
        (name, "GET" if method in ("getAPIList", "get_api_list") else method.upper())
        for file in root.rglob("*")
        if file.suffix in (".ts", ".py")
        for method, name in re.findall(pattern, file.read_text())
    }
    expected = {(name, method) for name, (method, _) in operations.items()}
    if expected != references:
        raise ValueError(f"{root}: unimplemented {sorted(expected - references)}, "
                         f"missing or changed operations {sorted(references - expected)}")


def write_routes(operations, js_file, py_file):
    js = [
        "// Generated by scripts/sdk/generate.py.",
        "import { path } from './utils/path';",
        "",
        "export const operations = {",
    ]
    py = ["# Generated by scripts/sdk/generate.py.", "OPERATIONS = {"]
    for name, (_, route) in sorted(operations.items()):
        parts = PARAMETER.split(route)
        arguments = [f"arg{index}" for index in range(len(parts) // 2)]
        value = json.dumps(route)
        if arguments:
            signature = ", ".join(f"{argument}: string | number" for argument in arguments)
            segments = json.dumps(parts[::2])
            value = f"({signature}) => path({segments}, {', '.join(arguments)})"
        js.append(f"  {json.dumps(name)}: {value},")
        py.append(f"    {json.dumps(name)}: {json.dumps(route)},")
    js.append("} as const;")
    py.append("}")
    if js_file is not None:
        js_file.write_text("\n".join(js) + "\n")
    if py_file is not None:
        py_file.write_text("\n".join(py) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("language", choices=("javascript", "python"))
    parser.add_argument("workdir", type=Path)
    args = parser.parse_args()
    root = args.workdir
    baselines = Path(__file__).resolve().parent
    spec = json.loads((root / "openapi.json").read_text())
    expected = {}
    for route, item in spec["paths"].items():
        for method, operation in item.items():
            if method in METHODS:
                name = operation["operationId"]
                if name in expected:
                    raise ValueError(f"Duplicate operationId: {name}")
                expected[name] = method.upper(), route

    operations = manifest(root / "operations.tsv")
    if not operations or operations != expected:
        raise ValueError("OpenAPI Generator manifest does not match the public OpenAPI contract")

    if args.language == "javascript":
        js = root / "javascript" / "src"
        py = None
        check_sources(js / "resources",
                      r'this\._client\.(\w+)\(\s*operations\["([^"]+)"\]', operations)
    else:
        js = None
        py = root / "python" / "src" / "gmt"
        baseline = json.loads((baselines / "python-surface.json").read_text())
        check_python_surface(py / "resources", operations, baseline)

    schemas = json.loads((baselines / "response-schemas.json").read_text())
    write_model_contract(spec, operations, js, py, root / "response-contract.json", schemas)
    write_routes(operations, js / "internal" / "operations.ts" if js else None,
                 py / "_operations.py" if py else None)


if __name__ == "__main__":
    main()
