"""Generate shared purchase response fields while preserving older payloads."""

import json
import keyword
import re


# These fields already have public types and documentation in the SDK wrappers.
PURCHASE_FIELDS = {
    "code_page", "id", "country_code", "created_at", "display_name", "emoji",
    "phone_number", "price", "purchase_source", "purchase_type", "status", "verification",
}
REQUIRED_CODE_PAGE_FIELDS = {"description", "logo_url", "support_url", "title"}
SCALARS = {
    "string": ("string", "str"), "integer": ("number", "int"),
    "number": ("number", "float"), "boolean": ("boolean", "bool"),
}


def render_field(field, name, objects):
    if field.get("type") == "object" and "properties" in field:
        if set(field) & {"$ref", "oneOf", "anyOf", "allOf"}:
            raise ValueError("Unsupported compound response model")
        render_object(name, field["properties"], set(field.get("required", [])), objects)
        ts, py = name, name
    elif field.get("type") == "array" and "items" in field:
        ts, py = render_field(field["items"], name + "Item", objects)
        ts, py = f"Array<{ts}>", f"List[{py}]"
    elif field.get("type") in SCALARS and not set(field) & {"$ref", "oneOf", "anyOf", "allOf"}:
        ts, py = SCALARS[field["type"]]
        if "enum" in field:
            values = field["enum"]
            if field["type"] != "string" or not values or not all(isinstance(value, str) for value in values):
                raise ValueError("Unsupported response enum")
            ts = " | ".join(json.dumps(value) for value in values)
            py = "Literal[" + ", ".join(repr(value) for value in values) + "]"
    else:
        raise ValueError(f"Unsupported response type for {name}")
    if field.get("nullable"):
        ts, py = f"{ts} | null", f"Optional[{py}]"
    return ts, py


def render_object(name, fields, required, objects):
    ts, py = [], []
    for field, schema in sorted(fields.items()):
        if not re.fullmatch(r"[a-z_][a-z0-9_]*", field) or keyword.iskeyword(field):
            raise ValueError(f"Unsupported response field name: {field}")
        child = name + "".join(part.capitalize() for part in field.split("_"))
        ts_type, py_type = render_field(schema, child, objects)
        optional = field not in required
        if optional and not schema.get("nullable"):
            py_type = f"Optional[{py_type}]"
        ts.append(f"  {json.dumps(field)}{'?' if optional else ''}: {ts_type};")
        py.append(f"    {field}: {py_type}" + (" = None" if optional else ""))
    if name in objects:
        raise ValueError(f"Duplicate generated model name: {name}")
    objects[name] = ts, py


def generate_purchase_models(model_fields, js, py):
    purchases = [fields for fields in model_fields if "code_page" in fields]
    pages = [fields["code_page"] for fields in purchases]
    if not pages or any(page != pages[0] for page in pages[1:]):
        raise ValueError("Unsupported code_page schema: purchase responses disagree")
    page = pages[0]
    if not page.get("nullable") or not REQUIRED_CODE_PAGE_FIELDS <= page["properties"].keys():
        raise ValueError("Unsupported code_page schema: existing fields must remain available")

    extra = purchases[0].keys() - PURCHASE_FIELDS
    if any(fields.keys() - PURCHASE_FIELDS != extra for fields in purchases[1:]):
        raise ValueError("getV1Purchases: OpenAPI response changed, shared purchase fields disagree")

    objects = {}
    try:
        # New fields stay optional in the SDK, including brand_name, so callers
        # can still read and construct the old response models.
        render_object("CodePage", page["properties"], REQUIRED_CODE_PAGE_FIELDS, objects)
        extensions = {field: purchases[0][field] for field in extra}
        if any(any(fields[field] != schema for field, schema in extensions.items()) for fields in purchases[1:]):
            raise ValueError("Shared purchase field schemas disagree")
        render_object("PurchaseResponseFields", extensions, set(), objects)
    except ValueError as error:
        raise ValueError(f"getV1Purchases: OpenAPI response changed, {error}") from error

    if js is not None:
        (js / "internal" / "code-page.ts").write_text(
            "// Generated by scripts/sdk/generate.py.\n\n" +
            "\n\n".join("\n".join([f"export interface {name} {{", *ts, "}"])
                         for name, (ts, _) in objects.items()) + "\n"
        )
    if py is not None:
        (py / "types" / "code_page.py").write_text(
            "# Generated by scripts/sdk/generate.py.\n\n"
            "from typing import List, Optional\n"
            "from typing_extensions import Literal\n\n"
            "from .._models import BaseModel\n\n\n" +
            "\n\n\n".join("\n".join([f"class {name}(BaseModel):", *(fields or ["    pass"])])
                             for name, (_, fields) in objects.items()) + "\n"
        )
    return extra
